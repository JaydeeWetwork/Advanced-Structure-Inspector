/**
 * Rebuild src/data/vanillaTgaTextures.js from the GitHub tree of the samples pin.
 *
 *   node scripts/index-vanilla-tga.mjs
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { githubTree, isDirectRun, readPackPin, repoRoot, writeIfChanged } from "./pinScriptUtil.mjs";

const BANNER_PREFIX = "/** Color TGA stems under resource_pack/ for ";

/**
 * @param {string} [tag]
 */
export async function planVanillaTgaList(tag = readPackPin("VANILLA_SAMPLES_TAG")) {
	const tree = await githubTree("Mojang", "bedrock-samples", tag);
	const tga = [];
	for (const node of tree) {
		const path = String(node.path || "");
		if (!path.startsWith("resource_pack/textures/") || !path.toLowerCase().endsWith(".tga")) continue;
		const stem = path.slice("resource_pack/".length).replace(/\.tga$/i, "");
		if (stem.toLowerCase().endsWith("_mers")) continue;
		tga.push(stem);
	}
	tga.sort();

	const outPath = join(repoRoot(), "src/data/vanillaTgaTextures.js");
	const previous = readFileSync(outPath, "utf8");
	const eol = previous.includes("\r\n") ? "\r\n" : "\n";
	const banner = `${BANNER_PREFIX}${tag}. *_mers companion maps are omitted. Regenerated by scripts/index-vanilla-tga.mjs */`;
	const rendered = JSON.stringify(tga, null, "\t").replace(/\n/g, eol);
	return {
		path: outPath,
		text: `${banner}${eol}export const VANILLA_SAMPLES_TGA_TAG = ${JSON.stringify(tag)};${eol}export const VANILLA_TGA_PATHS = new Set(${rendered});${eol}`,
		count: tga.length,
		tag
	};
}

/**
 * @param {string} [tag]
 */
export async function writeVanillaTgaList(tag) {
	const plan = await planVanillaTgaList(tag);
	const wrote = writeIfChanged(plan.path, plan.text);
	console.log(`${wrote ? "wrote" : "kept"} ${plan.count} TGA paths for ${plan.tag}`);
	return plan.count;
}

if (isDirectRun(import.meta.url)) {
	await writeVanillaTgaList();
}
